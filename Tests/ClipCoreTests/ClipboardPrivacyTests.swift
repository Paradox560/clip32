import AppKit
import XCTest
@testable import ClipCore

final class ClipboardPrivacyTests: XCTestCase {
    func testAllSupportedConfidentialAndTransientMarkersPreventCapture() async {
        await MainActor.run {
            let directory = FileManager.default.temporaryDirectory.appendingPathComponent("Clip32PrivacyTests-\(UUID().uuidString)")
            defer { try? FileManager.default.removeItem(at: directory) }
            let store = HistoryStore(directory: directory)
            defer { store.flush() }
            let pasteboard = NSPasteboard.withUniqueName()
            defer { pasteboard.releaseGlobally() }
            let monitor = ClipboardMonitor(store: store, pasteboard: pasteboard)
            let markers = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                           "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType"]
            for marker in markers {
                let item = NSPasteboardItem()
                XCTAssertTrue(item.setString("Synthetic private fixture", forType: .string))
                XCTAssertTrue(item.setData(Data(), forType: .init(marker)), marker)
                pasteboard.clearContents()
                XCTAssertTrue(pasteboard.writeObjects([item]))
                monitor.captureNow()
                XCTAssertTrue(store.entries.isEmpty, marker)
            }
            store.flush()
            XCTAssertFalse(FileManager.default.fileExists(atPath: store.historyURL.path))
        }
    }

    func testRestoreReceiptIdentifiesTheSelectedClipboardContents() async {
        await MainActor.run {
            let directory = FileManager.default.temporaryDirectory.appendingPathComponent("Clip32ReceiptTests-\(UUID().uuidString)")
            defer { try? FileManager.default.removeItem(at: directory) }
            let store = HistoryStore(directory: directory)
            let pasteboard = NSPasteboard.withUniqueName()
            defer { pasteboard.releaseGlobally() }
            let monitor = ClipboardMonitor(store: store, pasteboard: pasteboard)
            let entry = ClipboardEntry(items: [ClipboardItem(representations: [ClipboardRepresentation(type: NSPasteboard.PasteboardType.string.rawValue, data: Data("Selected fixture".utf8))])])
            XCTAssertTrue(monitor.restore(entry))
            XCTAssertEqual(monitor.restoredChangeCount, pasteboard.changeCount)
            let receipt = monitor.restoredChangeCount
            pasteboard.clearContents()
            pasteboard.setString("Later fixture", forType: .string)
            XCTAssertNotEqual(receipt, pasteboard.changeCount)
            XCTAssertFalse(monitor.restore(ClipboardEntry(items: [])))
            XCTAssertNil(monitor.restoredChangeCount)
        }
    }
}

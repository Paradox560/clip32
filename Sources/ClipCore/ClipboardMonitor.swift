import AppKit
import Combine
import Foundation

@MainActor
public final class ClipboardMonitor: ObservableObject {
    @Published public var isPaused = false {
        didSet {
            guard isPaused != oldValue else { return }
            // Copies made while paused must not be captured when capture resumes.
            lastChangeCount = pasteboard.changeCount
            if isPaused { stopPolling() }
            else { startPollingIfNeeded() }
        }
    }
    @Published public private(set) var notice: String?
    /// Receipt for the most recent successful restore, used to reject a stale paste.
    public private(set) var restoredChangeCount: Int?

    private let store: HistoryStore
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var timer: Timer?
    private var isStarted = false
    private var pollingGeneration: UUID?
    private let schedulePolling: (@escaping @MainActor () -> Void) -> Timer

    public static let supportedTypes: [NSPasteboard.PasteboardType] = [
        .string, .rtf, .rtfd, .html, .png, .tiff, .URL, .fileURL
    ]

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type"
    ]

    public convenience init(store: HistoryStore, pasteboard: NSPasteboard = .general) {
        self.init(store: store, pasteboard: pasteboard, schedulePolling: { action in
            let timer = Timer(timeInterval: 0.4, repeats: true) { _ in
                Task { @MainActor in action() }
            }
            timer.tolerance = 0.1
            RunLoop.main.add(timer, forMode: .common)
            return timer
        })
    }

    /// An injectable scheduler keeps lifecycle tests independent of wall-clock timing.
    init(store: HistoryStore, pasteboard: NSPasteboard,
         schedulePolling: @escaping (@escaping @MainActor () -> Void) -> Timer) {
        self.store = store
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
        self.schedulePolling = schedulePolling
    }

    deinit { timer?.invalidate() }

    public func start() {
        isStarted = true
        startPollingIfNeeded()
    }

    public func stop() {
        isStarted = false
        stopPolling()
    }

    private func startPollingIfNeeded() {
        guard isStarted, !isPaused, timer == nil else { return }
        let generation = UUID()
        pollingGeneration = generation
        timer = schedulePolling { [weak self] in
            guard let self, self.pollingGeneration == generation,
                  self.isStarted, !self.isPaused else { return }
            self.captureNow()
        }
    }

    private func stopPolling() {
        // Invalidate callbacks already queued by a timer before it was cancelled.
        pollingGeneration = nil
        timer?.invalidate()
        timer = nil
    }

    public func captureNow() {
        guard !isPaused else { return }
        let observedCount = pasteboard.changeCount
        guard observedCount != lastChangeCount else { return }
        lastChangeCount = observedCount
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return }

        if pasteboardItems.contains(where: { item in
            item.types.contains(where: { Self.ignoredTypes.contains($0.rawValue) })
        }) {
            notice = "A private or temporary clipboard item was skipped."
            return
        }

        var byteCount = 0
        var items: [ClipboardItem] = []
        for item in pasteboardItems {
            var representations: [ClipboardRepresentation] = []
            for type in Self.supportedTypes where item.types.contains(type) {
                guard let data = item.data(forType: type), !data.isEmpty else { continue }
                byteCount += data.count
                guard byteCount <= HistoryStore.maximumEntryBytes else {
                    notice = "This item is larger than 16 MB and was not saved. Your current clipboard is unchanged."
                    return
                }
                representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
            }
            guard !representations.isEmpty else {
                notice = "This clipboard format is not supported. Text, images, and copied files are supported."
                return
            }
            items.append(ClipboardItem(representations: representations))
        }

        // A deferred pasteboard provider may change the clipboard while data is being read.
        // Retry the new contents on the next poll rather than recording a mixed snapshot.
        guard pasteboard.changeCount == observedCount else { return }
        let entry = ClipboardEntry(sourceApp: NSWorkspace.shared.frontmostApplication?.localizedName, items: items)
        if store.insert(entry) { notice = nil }
    }

    @discardableResult
    public func restore(_ entry: ClipboardEntry) -> Bool {
        restoredChangeCount = nil
        guard !entry.items.isEmpty else { return false }
        var objects: [NSPasteboardItem] = []
        for savedItem in entry.items {
            let item = NSPasteboardItem()
            for representation in savedItem.representations {
                guard item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type)) else {
                    notice = "This entry could not be copied. Your current clipboard is unchanged."
                    return false
                }
            }
            objects.append(item)
        }
        let writeCount = pasteboard.clearContents()
        let success = pasteboard.writeObjects(objects)
        lastChangeCount = writeCount
        guard pasteboard.changeCount == writeCount else {
            notice = "The clipboard changed while restoring this item. Select it again."
            return false
        }
        if success { restoredChangeCount = writeCount }
        notice = success ? nil : "This entry could not be copied to the clipboard."
        return success
    }
}
